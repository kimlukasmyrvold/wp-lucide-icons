'use strict';

const fs = require('fs/promises');
const os = require('os');
const path = require('path');
const { Readable } = require('stream');
const { pipeline } = require('stream/promises');
const tar = require('tar');

const ROOT = path.resolve(__dirname, '..');
const MAP_PATH = path.join(
    ROOT,
    'src',
    'includes',
    'Icons',
    'Material',
    'material-symbols-outlined-map.php',
);
const PACKAGE = '@material-symbols/svg-400';

function innerSvg(svg) {
    return svg
        .replace(/<\?xml[^>]*>/gi, '')
        .replace(/<!DOCTYPE[^>]*>/gi, '')
        .replace(/<svg\b[^>]*>/i, '')
        .replace(/<\/svg>\s*$/i, '')
        .replace(/\s+/g, ' ')
        .trim();
}

function phpSingleQuoted(value) {
    return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

async function registryPackage(name, version) {
    const spec = version
        ? `${encodeURIComponent(name)}/${encodeURIComponent(version)}`
        : `${encodeURIComponent(name)}/latest`;
    const res = await fetch(`https://registry.npmjs.org/${spec}`);
    if (!res.ok) {
        throw new Error(`npm registry ${name}@${version || 'latest'}: ${res.status} ${res.statusText}`);
    }
    return res.json();
}

async function extractTarball(tarballUrl, destDir, filter) {
    const res = await fetch(tarballUrl);
    if (!res.ok) {
        throw new Error(`Download failed ${tarballUrl}: ${res.status} ${res.statusText}`);
    }

    await fs.mkdir(destDir, { recursive: true });
    await pipeline(
        Readable.fromWeb(res.body),
        tar.x({
            cwd: destDir,
            gzip: true,
            filter,
        }),
    );
}

async function collectIcons(extractDir) {
    const iconsDir = path.join(extractDir, 'package', 'outlined');
    const files = await fs.readdir(iconsDir);
    const icons = {};

    for (const file of files.sort()) {
        if (!file.endsWith('.svg')) {
            continue;
        }

        const name = file.slice(0, -4);
        const svg = await fs.readFile(path.join(iconsDir, file), 'utf8');
        const inner = innerSvg(svg);
        if (!inner) {
            console.warn(`Skipping empty SVG: ${file}`);
            continue;
        }

        icons[name] = inner;
    }

    return icons;
}

function generatePhp(version, icons) {
    const pairs = Object.entries(icons)
        .map(([name, inner]) => `        ${phpSingleQuoted(name)} => ${phpSingleQuoted(inner)},`)
        .join('\n');

    return `<?php

if (!\\defined('ABSPATH')) {
    exit;
}

/**
 * Generated by \`pnpm sync-icons\` from ${PACKAGE}@${version} (outlined).
 * Do not hand-edit; re-run the script instead.
 */
return [
    'version' => ${phpSingleQuoted(version)},
    'icons' => [
${pairs}
    ],
];
`;
}

async function main() {
    const requested = process.argv[2] || 'latest';
    console.log(`Resolving ${PACKAGE}@${requested}…`);

    const meta = await registryPackage(PACKAGE, requested === 'latest' ? undefined : requested);
    const version = meta.version;
    if (!version || !meta.dist || !meta.dist.tarball) {
        throw new Error(`${PACKAGE} metadata is missing version or tarball`);
    }

    const tmp = await fs.mkdtemp(path.join(os.tmpdir(), 'wp-material-symbols-'));

    try {
        console.log(`Downloading ${PACKAGE}@${version}…`);
        await extractTarball(meta.dist.tarball, tmp, (p) => {
            const normalized = p.replace(/\\/g, '/');
            return normalized.includes('/outlined/') && normalized.endsWith('.svg');
        });

        const icons = await collectIcons(tmp);
        const count = Object.keys(icons).length;
        if (count < 1) {
            throw new Error('No outlined SVG icons found in @material-symbols/svg-400');
        }

        await fs.mkdir(path.dirname(MAP_PATH), { recursive: true });
        await fs.writeFile(MAP_PATH, generatePhp(version, icons), 'utf8');

        console.log(`Wrote ${count} icons to ${path.relative(ROOT, MAP_PATH)}`);
        console.log(`Bundled Material Symbols version: ${version}`);
    } finally {
        await fs.rm(tmp, { recursive: true, force: true });
    }
}

main().catch((error) => {
    console.error(error.message || error);
    process.exit(1);
});
