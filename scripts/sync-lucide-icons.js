'use strict';

const fs = require('fs/promises');
const os = require('os');
const path = require('path');
const { Readable } = require('stream');
const { pipeline } = require('stream/promises');
const tar = require('tar');

const ROOT = path.resolve(__dirname, '..');
const ENUM_PATH = path.join(ROOT, 'src', 'includes', 'Icons', 'LucideIcon.php');

const PHP_RESERVED = new Set([
    '__halt_compiler', 'abstract', 'and', 'array', 'as', 'break', 'callable', 'case',
    'catch', 'class', 'clone', 'const', 'continue', 'declare', 'default', 'die', 'do',
    'echo', 'else', 'elseif', 'empty', 'enddeclare', 'endfor', 'endforeach', 'endif',
    'endswitch', 'endwhile', 'eval', 'exit', 'extends', 'final', 'finally', 'fn', 'for',
    'foreach', 'function', 'global', 'goto', 'if', 'implements', 'include', 'include_once',
    'instanceof', 'insteadof', 'interface', 'isset', 'list', 'match', 'namespace', 'new',
    'or', 'parent', 'print', 'private', 'protected', 'public', 'readonly', 'require',
    'require_once', 'return', 'self', 'static', 'switch', 'throw', 'trait', 'try', 'unset',
    'use', 'var', 'while', 'xor', 'yield', 'true', 'false', 'null', 'enum',
]);

function kebabToPascal(kebab) {
    return kebab
        .split(/[-_]/)
        .filter(Boolean)
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
        .join('');
}

function enumCaseName(kebab, used) {
    let name = kebabToPascal(kebab);

    if (!name || /^\d/.test(name) || PHP_RESERVED.has(name.toLowerCase())) {
        name = `${name || 'Icon'}Icon`;
    }

    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) {
        name = `Icon${name.replace(/[^A-Za-z0-9_]/g, '')}`;
    }

    let unique = name;
    let n = 2;
    while (used.has(unique)) {
        unique = `${name}${n}`;
        n += 1;
    }

    used.add(unique);
    return unique;
}

function innerSvg(svg) {
    return svg
        .replace(/<\?xml[^>]*>/gi, '')
        .replace(/<!DOCTYPE[^>]*>/gi, '')
        .replace(/<svg\b[^>]*>/i, '')
        .replace(/<\/svg>\s*$/i, '')
        .replace(/\s+/g, ' ')
        .trim();
}

function phpSingleQuoted(value) {
    return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

async function registryPackage(name, version) {
    const spec = version ? `${encodeURIComponent(name)}/${encodeURIComponent(version)}` : `${encodeURIComponent(name)}/latest`;
    const res = await fetch(`https://registry.npmjs.org/${spec}`);
    if (!res.ok) {
        throw new Error(`npm registry ${name}@${version || 'latest'}: ${res.status} ${res.statusText}`);
    }
    return res.json();
}

async function extractTarball(tarballUrl, destDir, filter) {
    const res = await fetch(tarballUrl);
    if (!res.ok) {
        throw new Error(`Download failed ${tarballUrl}: ${res.status} ${res.statusText}`);
    }

    await fs.mkdir(destDir, { recursive: true });
    await pipeline(
        Readable.fromWeb(res.body),
        tar.x({
            cwd: destDir,
            gzip: true,
            filter,
        }),
    );
}

async function collectIcons(extractDir) {
    const iconsDir = path.join(extractDir, 'package', 'icons');
    const files = await fs.readdir(iconsDir);
    const used = new Set();
    const icons = [];

    for (const file of files.sort()) {
        if (!file.endsWith('.svg')) {
            continue;
        }

        const kebab = file.slice(0, -4);
        const svg = await fs.readFile(path.join(iconsDir, file), 'utf8');
        const inner = innerSvg(svg);
        if (!inner) {
            console.warn(`Skipping empty SVG: ${file}`);
            continue;
        }

        icons.push({
            kebab,
            caseName: enumCaseName(kebab, used),
            inner,
        });
    }

    return icons;
}

function generatePhp(version, icons) {
    const cases = icons
        .map((icon) => `    case ${icon.caseName} = ${phpSingleQuoted(icon.kebab)};`)
        .join('\n');

    const arms = icons
        .map((icon) => `            self::${icon.caseName} => ${phpSingleQuoted(icon.inner)},`)
        .join('\n');

    return `<?php

namespace WPIcons\\Icons;

if (!\\defined('ABSPATH')) {
    exit;
}

/**
 * Generated by \`pnpm sync-icons\` from lucide-static@${version}.
 * Do not hand-edit icon cases or inner() arms; re-run the script instead.
 */
enum LucideIcon: string
{
    public const BUNDLED_VERSION = ${phpSingleQuoted(version)};

${cases}

    public function render(
        string|bool $hiddenOrTitle = true,
        int $widthOrSize = 24,
        ?int $height = null,
        string $color = 'currentColor',
        float|int|string $strokeWidth = 2,
    ): string {
        $options = new IconOptions(
            name: $this->value,
            size: $widthOrSize,
            height: $height,
            color: $color,
            strokeWidth: is_numeric($strokeWidth) ? (float) $strokeWidth : 2.0,
            hiddenOrTitle: $hiddenOrTitle,
        );

        return Svg::lucide($this->inner(), $options);
    }

    public static function fromName(string $name): ?self
    {
        return self::tryFrom(str_replace('_', '-', $name));
    }

    public static function html(
        self|string|null $icon,
        string|bool $hiddenOrTitle = true,
        int $widthOrSize = 24,
        ?int $height = null,
        string $color = 'currentColor',
        float|int|string $strokeWidth = 2,
    ): string {
        if ($icon instanceof self) {
            return $icon->render($hiddenOrTitle, $widthOrSize, $height, $color, $strokeWidth);
        }

        if (!\\is_string($icon) || $icon === '') {
            return '';
        }

        return self::fromName($icon)?->render($hiddenOrTitle, $widthOrSize, $height, $color, $strokeWidth) ?? '';
    }

    public function inner(): string
    {
        return match ($this) {
${arms}
        };
    }
}
`;
}

async function main() {
    const requested = process.argv[2] || 'latest';
    console.log(`Resolving lucide@${requested}…`);

    const meta = await registryPackage('lucide-static', requested === 'latest' ? undefined : requested);
    const version = meta.version;
    if (!version || !meta.dist || !meta.dist.tarball) {
        throw new Error('lucide-static metadata is missing version or tarball');
    }

    const tmp = await fs.mkdtemp(path.join(os.tmpdir(), 'wp-lucide-icons-'));
    const staticDir = path.join(tmp, 'lucide-static');

    try {
        console.log(`Downloading lucide-static@${version}…`);
        await extractTarball(meta.dist.tarball, staticDir, (p) => p.replace(/\\/g, '/').includes('/icons/') && p.endsWith('.svg'));

        const icons = await collectIcons(staticDir);
        if (icons.length < 1) {
            throw new Error('No SVG icons found in lucide-static');
        }

        await fs.writeFile(ENUM_PATH, generatePhp(version, icons), 'utf8');

        console.log(`Wrote ${icons.length} icons to ${path.relative(ROOT, ENUM_PATH)}`);
        console.log(`Bundled Lucide version: ${version}`);
    } finally {
        await fs.rm(tmp, { recursive: true, force: true });
    }
}

main().catch((error) => {
    console.error(error.message || error);
    process.exit(1);
});
